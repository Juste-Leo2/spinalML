/**
 * "Bebe Cadum" MNIST classifier, expressed purely through the high-level API.
 *
 * Trained topology (see Mnist/architecture.txt): Conv 5x5 (1->2) -> ReLU ->
 * MaxPool 2x2 -> Flatten -> Linear 288->10 -> softmax head. 2942 parameters,
 * 96% accuracy on the test set. Everything runs in BF16, features-last
 * convention, so the PyTorch input [1, 28, 28] becomes [28, 28, 1].
 *
 * The trained LogSoftmax head is omitted: Softmax1D requires power-of-2
 * channels (adder tree) and argmax(logits) = argmax(softmax(logits)), so the
 * raw 10 logits give the same prediction.
 */
case class Mnist(override val axiConfig: Axi4Config, override val tileHeight: Int = -1) extends Accelerator(
  dataType    = BF16(),
  inputShape  = Seq(28, 28, 1),
  modelSpec   = Seq(
    Conv2D(inChannels = 1, outChannels = 2, kernelSize = 5),
    ReLU(),
    MaxPool2D(poolSize = 2, stride = 2),
    Flatten(),
    Linear(inFeatures = 288, outFeatures = 10)
  ),
  axiConfig   = axiConfig
)

